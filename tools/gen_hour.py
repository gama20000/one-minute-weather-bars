"""Hour digit fonts: writes the Lato sizes used with and without weather, their real metrics
(tabular advance and ink rows measured on the rasterised glyphs, as Pebble's fontgen does),
the package.json resources and the host-harness tables.
Usage: python3 tools/gen_hour.py <size_with_weather> <size_without_weather>"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from render import hour_font, ink_box

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

def metrics(px):
    f = hour_font(px)
    advs = {f.glyph(ord(c))[4] for c in '0123456789'}
    assert len(advs) == 1, 'Lato digits must be tabular'
    top, bot = ink_box(f, '0123456789')
    return advs.pop(), top, bot

def main(s, l):
    ms, ml = metrics(s), metrics(l)
    with open(os.path.join(ROOT, 'src', 'c', 'hour_gen.h'), 'w') as h:
        h.write('// generated by tools/gen_hour.py - do not edit\n#pragma once\n')
        for tag, px, (adv, top, bot) in (('S', s, ms), ('L', l, ml)):
            h.write('#define HOUR_%s_PX %d\n#define HOUR_%s_DIGIT_W %d\n#define HOUR_%s_INK_TOP %d\n'
                    '#define HOUR_%s_INK_BOTTOM %d\n' % (tag, px, tag, adv, tag, top, tag, bot))
        h.write('#define RESOURCE_ID_HOUR_S RESOURCE_ID_LATO_HOUR_%d\n#define RESOURCE_ID_HOUR_L RESOURCE_ID_LATO_HOUR_%d\n' % (s, l))
    p = os.path.join(ROOT, 'package.json'); pkg = json.load(open(p))
    media = [m for m in pkg['pebble']['resources']['media'] if not m['name'].startswith('LATO_HOUR_')]
    fonts = [{'name': 'LATO_HOUR_%d' % px, 'type': 'font', 'file': 'fonts/Lato-Bold.ttf',
              'characterRegex': '[0-9]', 'targetPlatforms': ['emery']} for px in sorted({s, l})]
    pkg['pebble']['resources']['media'] = fonts + media
    json.dump(pkg, open(p, 'w'), indent=2, ensure_ascii=False); open(p, 'a').write('\n')
    # host harness
    bitmaps = [m for m in media if m['type'] == 'bitmap']
    with open(os.path.join(HERE, 'host', 'host_res.h'), 'w') as f:
        f.write('// generated for the host harness\n#pragma once\nenum {\n')
        for px in sorted({s, l}): f.write('  RESOURCE_ID_LATO_HOUR_%d = %d,\n' % (px, px))
        for i, m in enumerate(bitmaps): f.write('  RESOURCE_ID_%s = %d,\n' % (m['name'], 100 + i))
        f.write('};\nstatic const char *const HOST_RES_FILE[] = {\n')
        for m in bitmaps: f.write('  "%s",\n' % m['file'])
        f.write('};\n')
    with open(os.path.join(HERE, 'host', 'host_hour.h'), 'w') as f:
        f.write('#pragma once\n')
        for tag, px in (('S', s), ('L', l)):
            fo = hour_font(px)
            f.write('static const signed char ADV_HOUR_%s[256] = {%s};\n' % (
                tag, ','.join(str(fo.glyph(c)[4] if 48 <= c <= 57 else 0) for c in range(256))))
    print('hour sizes', s, ms, l, ml)

if __name__ == '__main__':
    main(int(sys.argv[1]), int(sys.argv[2]))
