"""Generates the curved calendar images (Pebble cannot rotate text at runtime):
weekday (PT/EN) along the top-left of the dial and the day of month (1-31) along the
top-right, rendered from Lato Bold (the hour font) with 4x supersampling. Each image is a 1-bit palette
PNG (transparent + white); the watch recolours the palette. Writes resources/images/cal/*
and src/c/curved_gen.h with the screen offsets. Run before `pebble build` when changed."""
import json, math, os, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from render import pf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
CX, CY, R = 100, 102, 103          # dial centre; text stands just outside the 100 px ring
# Both words sit on the corner diagonals through the dial centre (+-44.4 deg from 12 o'clock),
# mirror images of each other. The day number is narrow enough to also be centred radially
# (same gap to the ring as to the screen edges); the 3-letter weekday already fills its corner.
DIAG = math.degrees(math.atan2(CX, CY))
WDAY_MID, DAY_MID = -DIAG, DIAG    # degrees from 12 o'clock
WDAY_R, DAY_R = R, R + 2

PT = ['Dom', 'Seg', 'Ter', 'Qua', 'Qui', 'Sex', 'Sáb']
EN = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']

from PIL import ImageFont
SS = 4                                   # supersampling factor
LATO = os.path.join(ROOT, 'resources', 'fonts', 'Lato-Bold.ttf')
SIZE = 20                                # px on the watch (Lato Bold, same family as the hour)
FT = ImageFont.truetype(LATO, SIZE * SS)

def text_width(s):
    return FT.getlength(s) / SS

def glyph_rot(ch, ang):
    """Character rendered at SS x, rotated, ready to be pasted on the SS x canvas."""
    asc, desc = FT.getmetrics()
    w = int(FT.getlength(ch)) + 8 * SS
    im = Image.new('L', (w, asc + desc + 8 * SS), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(im).text((4 * SS, 4 * SS), ch, font=FT, fill=255)
    return im.rotate(-ang, resample=Image.BICUBIC, expand=True)

def curved(s, mid, R):
    canvas = Image.new('L', (200 * SS, 228 * SS), 0)
    span = math.degrees(text_width(s) / R)
    a = mid - span / 2
    for ch in s:
        adv = text_width(ch)
        da = math.degrees(adv / R)
        ang = a + da / 2
        rot = glyph_rot(ch, ang)
        asc, desc = FT.getmetrics()
        rr = R + (asc + desc) / SS * 0.42       # glyph centre a bit outside the ring
        x = (CX + math.sin(math.radians(ang)) * rr) * SS
        y = (CY - math.cos(math.radians(ang)) * rr) * SS
        canvas.paste(255, (int(round(x - rot.width / 2)), int(round(y - rot.height / 2))), rot)
        a += da
    small = canvas.resize((200, 228), Image.BOX).point(lambda v: 255 if v >= 100 else 0)
    box = small.getbbox()
    return small.crop(box), box[0], box[1]

def save(img, path):
    pal = Image.new('P', img.size, 0)
    pal.putpalette([0, 0, 0, 255, 255, 255] + [0] * 762)
    pal.paste(1, (0, 0), img.point(lambda v: 255 if v > 127 else 0))
    pal.save(path, transparency=0, bits=1, optimize=True)

def main():
    out = os.path.join(ROOT, 'resources', 'images', 'cal')
    os.makedirs(out, exist_ok=True)
    media, rows = [], []
    items = [('WD_PT_%d' % i, s, WDAY_MID, WDAY_R) for i, s in enumerate(PT)] + \
            [('WD_EN_%d' % i, s, WDAY_MID, WDAY_R) for i, s in enumerate(EN)] + \
            [('DAY_%d' % d, str(d), DAY_MID, DAY_R) for d in range(1, 32)]
    for name, s, mid, r in items:
        img, x, y = curved(s, mid, r)
        fn = name.lower() + '.png'
        save(img, os.path.join(out, fn))
        media.append({'name': name, 'type': 'bitmap', 'file': 'images/cal/' + fn,
                      'memoryFormat': '1BitPalette', 'spaceOptimization': 'memory',
                      'targetPlatforms': ['emery']})
        rows.append((name, x, y, img.width, img.height))
    pkg_path = os.path.join(ROOT, 'package.json')
    pkg = json.load(open(pkg_path))
    keep = [m for m in pkg['pebble']['resources']['media'] if not m['file'].startswith('images/cal/')]
    pkg['pebble']['resources']['media'] = keep + media
    json.dump(pkg, open(pkg_path, 'w'), indent=2, ensure_ascii=False)
    open(pkg_path, 'a').write('\n')
    with open(os.path.join(ROOT, 'src', 'c', 'curved_gen.h'), 'w') as h:
        h.write('// generated by tools/gen_curved.py - do not edit\n#pragma once\n')
        h.write('typedef struct { uint32_t res; int16_t x, y; } CurvedImg;\n')
        h.write('#define CURVED_ROW(n, x, y) { RESOURCE_ID_##n, x, y }\n')
        for grp, pre, n in (('WD_PT', 'WD_PT_', 7), ('WD_EN', 'WD_EN_', 7), ('DAY', 'DAY_', 31)):
            first = 0 if grp != 'DAY' else 1
            h.write('static const CurvedImg CURVED_%s[%d] = {\n' % (grp, n))
            for i in range(first, first + n):
                r = next(r for r in rows if r[0] == pre + str(i))
                h.write('  CURVED_ROW(%s, %d, %d),\n' % (r[0], r[1], r[2]))
            h.write('};\n')
    print('generated', len(items), 'images')

if __name__ == '__main__':
    main()
